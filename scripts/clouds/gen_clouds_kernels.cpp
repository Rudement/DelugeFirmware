// polyphase kernel tables, so the firmware does not build them at runtime.
// Host tool, not part of the firmware build:
//   g++ -O0 -o gen scripts/clouds/gen_clouds_kernels.cpp && ./gen > src/deluge/dsp/clouds_adapter_kernels.h
// The kernel code below is the generator clouds_adapter.cpp used to run on the unit, verbatim.
#include <cmath>
#include <cstdio>
#include <cstdint>
struct CloudsAdapter { static constexpr int32_t kKernelOversample = 128; static constexpr int32_t kDownTaps = 48; static constexpr int32_t kUpTaps = 32; };
namespace {
constexpr float kCutoffHz = 15500.0f;
constexpr double kKaiserBeta = 9.0;

/// Zeroth-order modified Bessel function, power series. Init-time only.
double besselI0(double x) {
	double sum = 1.0;
	double term = 1.0;
	double q = x * x / 4.0;
	for (int k = 1; k < 64; ++k) {
		term *= q / (static_cast<double>(k) * static_cast<double>(k));
		sum += term;
		if (term < sum * 1e-17) {
			break;
		}
	}
	return sum;
}

/// Kaiser-windowed sinc, cutoff kCutoffHz, on a grid of `gridRate` samples/s.
/// Tap i at fractional position frac sits at t = taps/2 - 1 - i + frac grid
/// samples from the point being computed.
void fillKernel(float* table, int32_t taps, double gridRate) {
	const double half = taps / 2.0;
	const double fc = kCutoffHz / gridRate; // cycles per grid sample
	const double i0Beta = besselI0(kKaiserBeta);
	for (int32_t p = 0; p <= CloudsAdapter::kKernelOversample; ++p) {
		for (int32_t i = 0; i < taps; ++i) {
			double t = half - 1.0 - i + static_cast<double>(p) / CloudsAdapter::kKernelOversample;
			double r = t / half;
			double w = (r * r <= 1.0) ? besselI0(kKaiserBeta * std::sqrt(1.0 - r * r)) / i0Beta : 0.0;
			double x = 2.0 * fc * t;
			double sinc = (std::fabs(x) < 1e-12) ? 1.0 : std::sin(M_PI * x) / (M_PI * x);
			table[p * taps + i] = static_cast<float>(2.0 * fc * sinc * w);
		}
	}
}


}
